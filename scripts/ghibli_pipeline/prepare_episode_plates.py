#!/usr/bin/env python3
"""
Generic Multi-Episode Ghibli Plate & Cutout Processor (`scripts/ghibli_pipeline/prepare_episode_plates.py`).

Supports ANY episode (old or upcoming) via a JSON manifest or CLI flags:
  - Generates procedural cold-press watercolor paper grain (`watercolor_paper_grain.png`)
  - Processes full-frame 2560x1440 background plates (auto-trimming corner watermarks)
  - Stitches seamless 4K+ horizontal architectural & floor panoramas with top-edge alpha feathering
  - Extracts edge-connected flood-fill alpha for tree/prop cutouts (NEVER global white-keying),
    with 3-pass morphological paper-halo choke, 5-step RGB fringe decontamination, and
    enclosed white-hole removal inside branch forks and basket handles
  - Slices 2x2 prop sheets automatically along center gutters
  - Emits TypeScript anchor metadata (`plateAnchors.ts`) for `<GhibliCutout>`

Usage:
  # Run Episode 3 default pipeline:
  python scripts/ghibli_pipeline/prepare_episode_plates.py --episode ep03

  # Run any episode with a manifest JSON:
  python scripts/ghibli_pipeline/prepare_episode_plates.py --manifest scripts/ghibli_pipeline/manifests/ep04_ghibli.json
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from PIL import Image

from prepare_ghibli_plates import (
    PROD_ROOT,
    extract_border_alpha,
    generate_paper_grain,
    main as run_ep03_default,
    process_courtyard_back,
    process_courtyard_floor,
    process_cutout,
    process_far_trees,
    process_full_plate,
    remove_enclosed_holes,
    resize_sharp,
    slice_props_sheet,
    trim_rgba,
)


def write_episode_anchors_ts(out_ts: Path, meta: dict[str, tuple[int, int, float, float]]) -> None:
    lines = [
        "// AUTO-GENERATED by scripts/ghibli_pipeline/prepare_episode_plates.py",
        "export interface CutoutAnchor {",
        "  width: number;",
        "  height: number;",
        "  anchorX: number;",
        "  anchorY: number;",
        "}",
        "",
        "export const GHIBLI_ANCHORS: Record<string, CutoutAnchor> = {",
    ]
    for name, (w, h, ax, ay) in meta.items():
        lines.append(f"  {name}: {{ width: {w}, height: {h}, anchorX: {ax:.4f}, anchorY: {ay:.4f} }},")
    lines.append("};")
    lines.append("")
    out_ts.parent.mkdir(parents=True, exist_ok=True)
    out_ts.write_text("\n".join(lines), encoding="utf-8")
    print(f"[OK] Wrote episode anchors metadata: {out_ts}")


def run_from_manifest(manifest_path: Path) -> None:
    cfg = json.loads(manifest_path.read_text(encoding="utf-8"))
    ep_slug: str = cfg["episode"]  # e.g. "ep04" or "episode04"
    img_dir = PROD_ROOT / "remotion_studio" / "public" / "images" / cfg.get("publicSubdir", f"ghibli_{ep_slug}")
    raw_dir = img_dir / "raw"
    anchors_ts = PROD_ROOT / "remotion_studio" / "src" / "ghibli_pipeline" / cfg.get("srcSubdir", ep_slug) / "plateAnchors.ts"

    img_dir.mkdir(parents=True, exist_ok=True)
    generate_paper_grain(img_dir / "watercolor_paper_grain.png")

    for plate in cfg.get("fullPlates", []):
        raw_name = plate["raw"] if isinstance(plate, dict) else plate
        out_name = plate.get("out", raw_name) if isinstance(plate, dict) else plate
        w = plate.get("width", 2560) if isinstance(plate, dict) else 2560
        h = plate.get("height", 1440) if isinstance(plate, dict) else 1440
        process_full_plate(raw_dir / raw_name, img_dir / out_name, width=w, height=h)

    for pano in cfg.get("panoramas", []):
        kind = pano["kind"]
        raw_p = raw_dir / pano["raw"]
        out_p = img_dir / pano.get("out", pano["raw"])
        if kind == "courtyard_back":
            process_courtyard_back(raw_p, out_p)
        elif kind == "courtyard_floor":
            process_courtyard_floor(raw_p, out_p)
        elif kind == "far_trees":
            process_far_trees(raw_p, out_p)
        else:
            raise ValueError(f"Unknown panorama kind '{kind}' in {manifest_path}")

    meta: dict[str, tuple[int, int, float, float]] = {}
    for cut in cfg.get("cutouts", []):
        name = cut["name"]
        raw_p = raw_dir / cut.get("raw", f"{name}.png")
        out_p = img_dir / f"{name}.png"
        meta[name] = process_cutout(
            raw_p,
            out_p,
            target_height=int(cut.get("targetHeight", 1200)),
            soft_shadow_bot_frac=float(cut.get("softShadowBotFrac", 0.20)),
            hole_min_area=int(cut.get("holeMinArea", 55)),
            hole_max_y_frac=float(cut.get("holeMaxYFrac", 0.82)),
            choke_light_halo=bool(cut.get("chokeLightHalo", True)),
        )

    if "propsSheet" in cfg:
        meta.update(slice_props_sheet(raw_dir / cfg["propsSheet"], img_dir))

    if meta:
        write_episode_anchors_ts(anchors_ts, meta)


def main() -> None:
    parser = argparse.ArgumentParser(description="Generic Multi-Episode Ghibli Plate Processor")
    parser.add_argument("--episode", default="ep03", help="Episode slug (default: ep03)")
    parser.add_argument("--manifest", type=Path, default=None, help="Path to episode Ghibli manifest JSON")
    args = parser.parse_args()

    if args.manifest is not None:
        run_from_manifest(args.manifest)
    elif args.episode in ("ep03", "episode03", "3"):
        run_ep03_default()
    else:
        default_manifest = Path(__file__).resolve().parent / "manifests" / f"{args.episode}_ghibli.json"
        if not default_manifest.exists():
            raise FileNotFoundError(
                f"No manifest found at {default_manifest}. Create one or pass --manifest <path.json>."
            )
        run_from_manifest(default_manifest)


if __name__ == "__main__":
    main()
