/**
 * A scene's exported sound event (S01_EVENTS, S02_EVENTS). The clock of `f` is the scene's own convention
 * (SCENE_EVENT_CLOCK, from each scene file's header): "real" = a REAL scene-local frame (absolute = scene start + f),
 * "story" = a story frame (the pauses before it are added here). An event can override it with `real: true` or
 * `clock: "real" | "story"`. `loopFrames` / `frames` / `dur` (any of them) make it a loop over that many frames of the
 * same clock (a footstep or hoof run). A sound that would run past the scene's audible end (bedEnd: into the chapter
 * break, or past the series fade) is cut there with a short fade, so nothing leaks into the next scene or the outro.
 */
interface SceneEvent {
  id?: string;
  f: number;
  file: string;
  volume: number;
  real?: boolean;
  clock?: string;
  loopFrames?: number;
  frames?: number;
  dur?: number;
  fadeIn?: number;
  fadeOut?: number;
  rate?: number;
  gate?: boolean;
}
/** An event object, accepting `at` / `frame` for `f`, `src` for `file` and `vol` for `volume` (normalised here). */
const asEvent = (e: unknown): SceneEvent | null => {
  if (!e || typeof e !== "object") return null;
  const o = e as Record<string, unknown>;
  const f = [o.f, o.at, o.frame].find((v) => typeof v === "number") as number | undefined;
  const file = [o.file, o.src].find((v) => typeof v === "string") as string | undefined;
  const volume = [o.volume, o.vol].find((v) => typeof v === "number") as number | undefined;
  if (f === undefined || file === undefined || volume === undefined) return null;
  return { ...(o as Partial<SceneEvent>), f, file, volume };
};
/**
 * Reads a scene module's event list without a hard import (the scene agents add it), as an array or an object of
 * events (or of arrays of events). Missing -> the local fallback (empty).
 */
const readEvents = (mod: unknown, name: string, fallback: SceneEvent[]): SceneEvent[] => {
  const v = (mod as Record<string, unknown>)[name];
  if (v === undefined || v === null) return fallback;
  const out: SceneEvent[] = [];
  const visit = (x: unknown, key?: string) => {
    if (Array.isArray(x)) {
      x.forEach((y) => visit(y));
      return;
    }
    const ev = asEvent(x);
    if (ev) out.push(key && !ev.id ? { ...ev, id: key } : ev);
    else if (x && typeof x === "object") Object.entries(x as Record<string, unknown>).forEach(([k, y]) => visit(y, k));
  };
  visit(v);
  if (out.length === 0) console.warn(`Episode05: ${name} has no readable sound events ({ f, file, volume }); none placed`);
  return out;
};
