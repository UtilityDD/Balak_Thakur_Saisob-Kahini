/**
 * A voice clip (EP05_AUDIO) counts as speech from its start to its end; gaps shorter than DUCK_MERGE stay ducked so a
 * bed never pumps between two lines (20, so every 24-frame pause still opens). The level moves over DUCK_RAMP frames.
 */
const DUCK_RAMP = 10;
const DUCK_MERGE = 20;
/** No bed rises above this in the quiet (plan "Sound beds": open level capped at 0.25; AUD-02/03). */
const OPEN_CAP = 0.25;
const SPEECH: [number, number][] = (() => {
  const spans = EP05_AUDIO.map((a) => [a.startFrame, a.startFrame + a.frames] as [number, number]).sort((x, y) => x[0] - y[0]);
  const merged: [number, number][] = [];
  for (const s of spans) {
    const last = merged[merged.length - 1];
    if (last && s[0] - last[1] < DUCK_MERGE) last[1] = Math.max(last[1], s[1]);
    else merged.push([s[0], s[1]]);
  }
  return merged;
})();
/** 1 while a voice is speaking, 0 in a pause, eased in between (over `ramp` frames, default DUCK_RAMP). */
const speechAmount = (frame: number, ramp = DUCK_RAMP): number => {
  let amt = 0;
  for (const [a, b] of SPEECH) {
    if (frame < a - ramp) break;
    let t = 0;
    if (frame >= a && frame <= b) t = 1;
    else if (frame < a) t = (frame - (a - ramp)) / ramp;
    else if (frame <= b + ramp) t = 1 - (frame - b) / ramp;
    amt = Math.max(amt, ease(t));
  }
  return amt;
};
/** A level that sits at `open` (at most OPEN_CAP) in the quiet and at `under` under a voice. */
const ducked = (open: number, under: number, frame: number, ramp = DUCK_RAMP) => {
  const o = Math.min(OPEN_CAP, open);
  return o + (Math.min(o, under) - o) * speechAmount(frame, ramp);
};

