/**
 * Each layer loops over its bed's window at `under` under a voice and `open` in the quiet; `pauseOpen` overrides the
 * open level inside one pause of `pauseScene`. `inFrom` starts a layer later than its bed (fading in over `frames`);
 * `outAt` fades a layer out before its bed ends; `gate` multiplies the level by an extra 0..1 curve (absolute frame).
 */
interface BedLayer {
  file: string;
  under: number;
  open: number;
  pauseOpen?: Record<number, number>;
  inFrom?: { from: number; frames: number };
  outAt?: { from: number; frames: number };
  gate?: (abs: number) => number;
}
interface Bed {
  name: string;
  from: number; // absolute
  to: number; // absolute (exclusive)
  fadeIn: number;
  fadeOut: number;
  pauseScene?: string;
  layers: BedLayer[];
}

/** Where a scene's beds end: a few frames into the chapter-break black, else as the next scene's picture takes over. */
const BED_TAIL = 6;
const bedEnd = (sceneId: string): number => {
  const b = breakAfter(sceneId);
  if (b) return b.startFrame + BED_TAIL;
  // a scene that keeps drawing (and fading) through its overlap with the next one: its sound fades with it
  if (SCENE_FADE[sceneId]?.fadeToSceneEnd) return sceneEnd(sceneId) + BED_TAIL;
  const i = EP05_SCENES.findIndex((s) => s.sceneId === sceneId);
  const next = EP05_SCENES[i + 1];
  return Math.min(sceneEnd(sceneId), next ? next.startFrame : Infinity) + BED_TAIL;
};

