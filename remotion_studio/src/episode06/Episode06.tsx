/** A sound placed on the absolute timeline. */
interface PlacedSfx {
  file: string;
  volume: number;
  from: number;
  frames?: number;
  fadeIn?: number;
  fadeOut?: number;
}
const CUT_FADE = 12;
const LOOP_FILES = new Set(["birds_village", "wind_soft", "children_far_loop", "hens_cluck_loop"]);
/** A bed recording placed as a one-shot (d2_breeze: wind_soft) plays as a gust: at most GUST frames, eased in and out. */
const GUST = { frames: 48, fadeIn: 10, fadeOut: 18 };
/** Both scenes export REAL scene-local frames (their headers): absolute = scene start + f. Cut at the audible end. */
const placeEvent = (scene: string, e: SceneEvent): PlacedSfx => {
  const file = normSfx(e.file);
  const isLoop = e.loopFrames !== undefined && e.loopFrames > 0;
  const cap = isLoop ? LOOP_MAX : ONE_SHOT_MAX;
  const from = sceneStart(scene) + e.f;
  let frames = isLoop ? e.loopFrames : undefined;
  let fadeIn: number | undefined;
  let fadeOut: number | undefined;
  if (frames === undefined && LOOP_FILES.has(sfxName(file))) {
    frames = Math.min(GUST.frames, Math.ceil(sfxSeconds(file) * 24));
    fadeIn = GUST.fadeIn;
    fadeOut = GUST.fadeOut;
  }
  const until = bedEnd(scene) - from;
  const natural = frames ?? Math.ceil(sfxSeconds(file) * 24);
  if (natural > until) {
    if (frames === undefined) fadeIn = 1;
    frames = Math.max(0, until);
    fadeOut = Math.min(CUT_FADE, Math.max(1, Math.floor(frames / 2)));
  }
  return { file, volume: Math.min(cap, e.volume), from, frames, fadeIn, fadeOut };
};

