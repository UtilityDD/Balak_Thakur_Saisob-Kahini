/** The subtitle cue of a scene containing `snippet` (undefined if none). */
const phraseCue = (sceneId: string, snippet: string) => {
  const i = EP06_SCENES.findIndex((s) => s.sceneId === sceneId);
  const s = EP06_SCENES[i];
  const next = EP06_SCENES[i + 1];
  if (!s) return undefined;
  const end = Math.min(s.startFrame + s.durationFrames, next ? next.startFrame : Infinity);
  return EP06_CUES.find((q) => q.from >= s.startFrame && q.from < end && q.text.includes(snippet));
};
/** Absolute frame where the first subtitle phrase of a scene containing `snippet` starts (fallback: scene-local). */
const phraseAbs = (sceneId: string, snippet: string, fallbackLocal: number): number =>
  phraseCue(sceneId, snippet)?.from ?? sceneStart(sceneId) + fallbackLocal;
/**
 * Absolute frame of a WORD inside a phrase, by its character position in the cue (the cues are phrase-level). Checked
 * against the voice: "বাঁচিয়ে দিলেন" lands where the voice resumes after its silence in 01a_p3 (silencedetect, 3.49 to 4.18 s).
 */
const wordAbs = (sceneId: string, phraseSnippet: string, word: string, fallbackLocal: number): number => {
  const c = phraseCue(sceneId, phraseSnippet);
  const k = c ? c.text.indexOf(word) : -1;
  if (!c || k < 0) return sceneStart(sceneId) + fallbackLocal;
  return Math.round(c.from + ((c.to - c.from) * k) / c.text.length);
};
/** The gap of a scene that holds the beat `beatId` (scenes have several "after" gaps: find them by beat, not by kind). */
const gapByBeat = (scene: string, beatId: string) => EP06_GAPS.find((g) => g.sceneId === scene && g.beats.some((b) => b.id === beatId));
/** Absolute start of a gap (by one of its beat ids). */
const gapStart = (scene: string, beatId: string, fallback: number) => gapByBeat(scene, beatId)?.startFrame ?? fallback;
/** Absolute start of a gap BEAT (story frames run 1:1 inside a gap, so its offset from the gap start is real frames). */
const beatStart = (scene: string, beatId: string, fallback: number) => {
  const g = gapByBeat(scene, beatId);
  const b = g?.beats.find((x) => x.id === beatId);
  return g && b ? g.startFrame + (b.fromStory - g.fromStory) : fallback;
};
const pauseStartAbs = (scene: string, index: number, fallback: number) => {
  const w = pauseWindow(scene, index);
  return w ? sceneStart(scene) + w.start : fallback;
};

