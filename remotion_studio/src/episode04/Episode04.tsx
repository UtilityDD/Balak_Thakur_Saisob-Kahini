/** Story frame -> real local frame of a scene (pauses before it added; story frames already include gaps). */
const storyReal = (sceneId: string, story: number): number => storyToReal(story, pausesFor4(sceneId));

/** Pause `index` (0-based, sorted by atStory) of a scene as a real local window, or undefined before it exists. */
const pauseWindow = (sceneId: string, index: number): { start: number; end: number; frames: number } | undefined => {
  const p = pausesFor4(sceneId)[index];
  if (!p) return undefined;
  const start = p.startFrame - sceneStart(sceneId);
  return { start, end: start + p.frames, frames: p.frames };
};

/** The chapter break after a scene (absolute window), if the generator wrote one. */
const breakAfter = (sceneId: string): Ep04Break | undefined => BREAKS.find((b) => b.after === sceneId);

/** An action-gap beat of a scene as a real local window (scene 03 AG2: a_dhoop, b_ask, c_inside, d_drink). */
const gapBeat = (sceneId: string, id: string): { start: number; frames: number } | undefined => {
  for (const g of GAPS) {
    if (g.sceneId !== sceneId) continue;
    const b = g.beats.find((x) => x.id === id);
    if (b) return { start: storyReal(sceneId, b.fromStory), frames: b.frames };
  }
  return undefined;
};

/** Real local frame where the first subtitle phrase of a scene containing `snippet` starts (undefined if none). */
const phraseLocal = (sceneId: string, snippet: string): number | undefined => {
  const i = EP04_SCENES.findIndex((s) => s.sceneId === sceneId);
  const s = EP04_SCENES[i];
  const next = EP04_SCENES[i + 1];
  if (!s) return undefined;
  const end = Math.min(s.startFrame + s.durationFrames, next ? next.startFrame : Infinity);
  const c = EP04_CUES.find((q) => q.from >= s.startFrame && q.from < end && q.text.includes(snippet));
  return c ? c.from - s.startFrame : undefined;
};

/** 0 while the scene's story clock is held (inside one of its pauses), 1 otherwise, with short ramps. */
const GATE_RAMP = 5;
const storyRunning = (sceneId: string, absFrame: number): number => {
  let g = 1;
  for (const p of pausesFor4(sceneId)) {
    const a = p.startFrame;
    const b = p.startFrame + p.frames;
    const d = absFrame < a ? a - absFrame : absFrame > b ? absFrame - b : 0;
    g = Math.min(g, Math.min(1, d / GATE_RAMP));
  }
  return g;
};

const ease = (t: number) => 0.5 - 0.5 * Math.cos(Math.PI * Math.min(1, Math.max(0, t)));

